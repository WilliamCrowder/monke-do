"""Write the addon's generated data files (docs/DATA_CONTRACT.md sections 2 and 3).

This is the only writer of addon/MonkeDo/Data/*.lua. The output is byte-for-byte
deterministic for the same database and arguments (sorted ids, fixed field order,
"\\n" line endings, no timestamps beyond the `generated` date you pass), so a diff of
MonkeDB.lua between releases shows exactly which quests changed.
"""

from __future__ import annotations

import json
import sqlite3
from datetime import datetime, timezone
from pathlib import Path

from pipeline import db, rules
from pipeline.llm.summarize import get_summary
from pipeline.validate import load_context

DB_FILE = "MonkeDB.lua"
META_FILE = "MonkeDB_Meta.lua"
HEADER = (
    "-- GENERATED by pipeline/export.py. Do not edit.\n"
    "-- Monke Do quest data. Licensed GPL-3.0-only; see LICENSE and CREDITS.txt in this folder.\n"
    "-- Derived in part from the Questie database (https://github.com/Questie/QuestieDB, GPLv3):\n"
    "-- quest titles, objective sentences, target and turn-in names. Modified by the Monke Do\n"
    "-- pipeline, which adds the summaries and task lines.\n"
)

_LUA_ESCAPES = {"\\": "\\\\", '"': '\\"', "\n": "\\n", "\r": "\\r"}


def lua_string(s: str) -> str:
    """`s` as a double-quoted Lua 5.1 string literal.

    Backslash, double quote, newline and CR get their named escapes; every other
    control character becomes a three-digit decimal escape (three digits so a following
    digit cannot be read as part of it). Everything else, including non-ASCII, passes
    through: the file is UTF-8 and so are WoW's strings.
    """
    out = []
    for ch in s:
        if ch in _LUA_ESCAPES:
            out.append(_LUA_ESCAPES[ch])
        elif ord(ch) < 32 or ord(ch) == 127:
            out.append(f"\\{ord(ch):03d}")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def _lua_list(items: list[str]) -> str:
    return "{ " + ", ".join(lua_string(i) for i in items) + " }"


def _usable_summary(row: sqlite3.Row | None) -> dict | None:
    """The parsed summary when it passed validation, else None (rule-based fallback)."""
    if row is None or row["status"] != "ok" or not row["json"]:
        return None
    try:
        summary = json.loads(row["json"])
    except ValueError:
        return None
    return summary if isinstance(summary, dict) and summary.get("tasks") else None


def build_record(quest: sqlite3.Row, objectives: list, summary: dict | None) -> dict | None:
    """The MonkeDB fields for one quest, or None when there is nothing worth shipping.

    Without a valid summary the quest still gets rule-based monke bullets, but only when
    they say something the addon cannot say by itself: with no structured objectives and
    no turn-in NPC the only bullet would be the generic turn-in line, which the addon
    already appends when a quest has no record.

    `tp` holds the plain-voice objective bullets, one per structured objective, from the
    same templates as the addon's Rules.lua. Plain voice needs them only before a quest is
    accepted, when the game has no live objectives to build bullets from.
    """
    k = len(objectives)
    npc = quest["turnin_npc"]
    kind = quest["turnin_kind"] if "turnin_kind" in quest.keys() else None
    record: dict = {}
    if summary is not None:
        record["l"] = summary.get("lore_monke")
        record["p"] = summary.get("lore_plain")
        record["t"] = list(summary["tasks"])
        record["g"] = summary.get("group_line")
    elif k or npc:
        record["t"] = rules.tasks_for(objectives, npc, rules.MONKE, kind)
    else:
        return None
    if k:
        record["tp"] = [rules.task_for(o, rules.PLAIN) for o in objectives]
    record["n"] = k
    record["e"] = npc
    record["d"] = bool(npc) and kind in ("other", "object")
    return record


def _record_line(quest_id: int, record: dict) -> str:
    """One line of MonkeDB: fields in contract order l, p, t, tp, n, e, d, g, v; absent ones
    omitted."""
    parts = []
    for key in ("l", "p"):
        if record.get(key):
            parts.append(f"{key} = {lua_string(record[key])}")
    if record.get("t"):
        parts.append(f"t = {_lua_list(record['t'])}")
    if record.get("tp"):
        parts.append(f"tp = {_lua_list(record['tp'])}")
    if record.get("n"):
        parts.append(f"n = {int(record['n'])}")
    if record.get("e"):
        parts.append(f"e = {lua_string(record['e'])}")
    if record.get("d"):
        parts.append("d = true")
    if record.get("g"):
        parts.append(f"g = {lua_string(record['g'])}")
    parts.append(f"v = {db.SCHEMA_VERSION}")
    return f"  [{quest_id}] = {{ " + ", ".join(parts) + " },\n"


def _bucket(quest_id: int) -> str:
    return "vanilla" if quest_id < db.NEW_ID_THRESHOLD else "new"


def write(
    conn: sqlite3.Connection,
    out_dir: Path,
    *,
    build: str,
    generated: str | None = None,
    prompt_version: str = "v1",
) -> dict:
    """Write MonkeDB.lua and MonkeDB_Meta.lua into `out_dir` and return the coverage split.

    Coverage is what the plan asks each release to report: quests with lore, with tasks
    only, and title only (not exported), each split into vanilla ids (< 90000) and
    Forever-new ids (>= 90000).
    """
    coverage = {name: {"vanilla": 0, "new": 0} for name in ("lore", "tasks_only", "title_only")}
    lines = [HEADER, "MonkeDB = {\n"]
    count = 0
    for quest in conn.execute("SELECT * FROM quests ORDER BY id").fetchall():
        ctx = load_context(conn, quest)
        summary = _usable_summary(
            get_summary(conn, quest["id"], quest["text_hash"], prompt_version, ctx.fingerprint()))
        record = build_record(quest, ctx.objectives, summary)
        if record is None:
            coverage["title_only"][_bucket(quest["id"])] += 1
            continue
        has_lore = bool(record.get("l") or record.get("p"))
        coverage["lore" if has_lore else "tasks_only"][_bucket(quest["id"])] += 1
        lines.append(_record_line(quest["id"], record))
        count += 1
    lines.append("}\n")

    generated = generated or datetime.now(timezone.utc).strftime("%Y-%m-%d")
    meta = (
        f"{HEADER}MonkeDB_Meta = {{ build = {lua_string(build or 'unknown')}, "
        f"generated = {lua_string(generated)}, count = {count}, "
        f"schema = {db.SCHEMA_VERSION}, prompt = {lua_string(prompt_version)} }}\n"
    )
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    # write_bytes, not write_text: Windows must not turn "\n" into "\r\n".
    (out_dir / DB_FILE).write_bytes("".join(lines).encode("utf-8"))
    (out_dir / META_FILE).write_bytes(meta.encode("utf-8"))
    return {"count": count, "out_dir": str(out_dir), **coverage}


def format_coverage(result: dict) -> str:
    """The coverage split as the three lines the CLI prints after an export."""
    rows = (("with lore", "lore"), ("tasks only", "tasks_only"),
            ("title only (not exported)", "title_only"))
    return "\n".join(
        f"{label:<26} vanilla (<{db.NEW_ID_THRESHOLD}): {result[key]['vanilla']:>5}   "
        f"new (>={db.NEW_ID_THRESHOLD}): {result[key]['new']:>5}"
        for label, key in rows
    )
