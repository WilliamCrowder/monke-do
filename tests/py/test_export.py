NASTY = 'He said "hi"\\ and\nleft\r\tfast \x01\x7f 9 café 猫'


def add_quest(conn, quest_id: int, title: str, objectives_text: str | None = None,
              npc: str | None = None, objectives: list[tuple[str, str, int]] = ()) -> None:
    db.upsert_source_row(conn, db.QuestRow(
        id=quest_id, source="questie", title=title, objectives_text=objectives_text,
        turnin_npc=npc,
    ))
    db.replace_objectives(conn, quest_id, [
        db.Objective(quest_id=quest_id, idx=i, type=kind, target_name=name, amount=amount,
                     amount_source="text", source="questie")
        for i, (kind, name, amount) in enumerate(objectives, start=1)
    ])


def add_summary(conn, quest_id: int, summary: dict, status: str = "ok", stale: bool = False) -> None:
    quest = conn.execute("SELECT * FROM quests WHERE id = ?", (quest_id,)).fetchone()
    context_hash = "0000000000000000" if stale else validate.load_context(conn, quest).fingerprint()
    summarize.save_summary(conn, quest_id, quest["text_hash"], "v1", model="test",
                           summary_json=json.dumps(summary), status=status, errors=[], attempts=1,
                           context_hash=context_hash)


S214 = {"lore_monke": "Scout Riell want 10 Red Silk Bandanas. Monke go get.",
        "lore_plain": "Scout Riell needs 10 Red Silk Bandanas.",
        "tasks": ["Grab 10 Red Silk Bandana.", "Go back to Scout Riell."], "group_line": None}


def make_db():
    conn = db.connect()
    # Inserted out of id order on purpose: the file must still be sorted.
    add_quest(conn, 90010, "New And Shiny", "Defeat the Warden.", "Keeper Ash",
              [("monster", "The Warden", 1)])
    add_quest(conn, 214, "Red Silk Bandanas", "Bring 10 Red Silk Bandanas to Scout Riell.",
              "Scout Riell", [("item", "Red Silk Bandana", 10)])
    add_quest(conn, 7, "Kobold Camp Cleanup", "Kill 8 Kobold Vermin.", "Marshal McBride",
              [("monster", "Kobold Vermin", 8)])
    add_quest(conn, 9, "Rejected One", "Kill 3 Wolves.", None, [("monster", "Wolf", 3)])
    add_quest(conn, 300, "Title Only")
    add_quest(conn, 90020, "New Title Only")
    add_quest(conn, 301, "No Structure", "Speak with someone.", None)
    db.resolve_quests(conn)
    add_summary(conn, 214, S214)
    add_summary(conn, 9, {**S214, "lore_monke": "SHOULD NOT SHIP"}, status="rejected")
    add_summary(conn, 301, {"lore_monke": "Monke talk.", "lore_plain": "Go and talk.",
                            "tasks": ["Go back. Get shiny."], "group_line": "Bring friends."})
    return conn


def load_lua(out_dir: Path):
    runtime = lua51.LuaRuntime()
    for name in (export.DB_FILE, export.META_FILE):
        runtime.execute((out_dir / name).read_bytes().decode("utf-8"))
    return runtime.globals()


# ---------------------------------------------------------------- lua_string


@pytest.mark.parametrize(
    ("raw", "literal"),
    [
        ("plain", '"plain"'),
        ('say "hi"', '"say \\"hi\\""'),
        ("back\\slash", '"back\\\\slash"'),
        ("line\nbreak", '"line\\nbreak"'),
        ("carriage\rreturn", '"carriage\\rreturn"'),
        ("tab\there", '"tab\\009here"'),
        ("nul\x00 then 7", '"nul\\000 then 7"'),
        ("ctrl\x019", '"ctrl\\0019"'),  # three digits, so the 9 stays a separate character
        ("del\x7f", '"del\\127"'),
        ("café", '"café"'),
        ("", '""'),
    ],
)
def test_lua_string_escaping(raw: str, literal: str) -> None:
    assert export.lua_string(raw) == literal


@pytest.mark.parametrize("raw", [NASTY, "]]", "--[[ not a comment", "\\n", "\\", '"', "%d"])
def test_lua_string_round_trips_through_real_lua(raw: str) -> None:
    runtime = lua51.LuaRuntime(encoding="utf-8")
    assert runtime.eval(export.lua_string(raw)) == raw


