def test_file_layout_ordering_and_field_omission(tmp_path: Path) -> None:
    export.write(make_db(), tmp_path, build="1.60.1.69913", generated="2026-10-01")
    text = (tmp_path / export.DB_FILE).read_text(encoding="utf-8")
    lines = text.splitlines()
    assert lines[0] == "-- GENERATED by pipeline/export.py. Do not edit."
    lines = [l for l in lines if not l.startswith("--")]  # the notice header is prose
    assert lines == [
        "MonkeDB = {",
        '  [7] = { t = { "Bonk 8 Kobold Vermin.", "Go back to Marshal McBride." }, n = 1, '
        'e = "Marshal McBride", v = 3 },',
        '  [9] = { t = { "Bonk 3 Wolf.", "Go back. Get shiny." }, n = 1, v = 3 },',
        '  [214] = { l = "Scout Riell want 10 Red Silk Bandanas. Monke go get.", '
        'p = "Scout Riell needs 10 Red Silk Bandanas.", '
        't = { "Grab 10 Red Silk Bandana.", "Go back to Scout Riell." }, n = 1, '
        'e = "Scout Riell", v = 3 },',
        '  [301] = { l = "Monke talk.", p = "Go and talk.", t = { "Go back. Get shiny." }, '
        'g = "Bring friends.", v = 3 },',
        '  [90010] = { t = { "Bonk The Warden.", "Go back to Keeper Ash." }, n = 1, '
        'e = "Keeper Ash", v = 3 },',
        "}",
    ]
    assert "SHOULD NOT SHIP" not in text  # rejected summaries never reach players
    assert "[300]" not in text and "[90020]" not in text  # neither lore nor tasks: not exported


def test_bytes_are_utf8_lf_only_and_deterministic(tmp_path: Path) -> None:
    conn = make_db()
    add_summary(conn, 7, {"lore_monke": NASTY, "lore_plain": "x", "tasks": ["a", "b"],
                          "group_line": None})
    export.write(conn, tmp_path / "a", build="b1", generated="2026-10-01")
    export.write(conn, tmp_path / "b", build="b1", generated="2026-10-01")
    for name in (export.DB_FILE, export.META_FILE):
        first = (tmp_path / "a" / name).read_bytes()
        assert first == (tmp_path / "b" / name).read_bytes()
        assert b"\r" not in first and first.endswith(b"\n") and not first.startswith(b"\xef\xbb\xbf")
    assert "café 猫".encode("utf-8") in (tmp_path / "a" / export.DB_FILE).read_bytes()


def test_exported_files_are_valid_lua_51(tmp_path: Path) -> None:
    conn = make_db()
    add_summary(conn, 7, {"lore_monke": NASTY, "lore_plain": "x", "tasks": ["a", "b"],
                          "group_line": None})
    export.write(conn, tmp_path, build="1.60.1.69913", generated="2026-10-01")
    g = load_lua(tmp_path)
    assert g.MonkeDB[214].l == "Scout Riell want 10 Red Silk Bandanas. Monke go get."
    assert g.MonkeDB[214].p == "Scout Riell needs 10 Red Silk Bandanas."
    assert list(g.MonkeDB[214].t.values()) == ["Grab 10 Red Silk Bandana.", "Go back to Scout Riell."]
    assert (g.MonkeDB[214].n, g.MonkeDB[214].e, g.MonkeDB[214].v) == (1, "Scout Riell", 3)
    assert g.MonkeDB[214].g is None
    assert g.MonkeDB[7].l == NASTY
    assert g.MonkeDB[9].l is None and g.MonkeDB[9].e is None and g.MonkeDB[9].n == 1
    assert g.MonkeDB[301].n is None and g.MonkeDB[301].g == "Bring friends."
    assert g.MonkeDB[300] is None
    assert sorted(g.MonkeDB.keys()) == [7, 9, 214, 301, 90010]


def test_meta_file(tmp_path: Path) -> None:
    export.write(make_db(), tmp_path, build="1.60.1.69913", generated="2026-10-01")
    text = (tmp_path / export.META_FILE).read_text(encoding="utf-8")
    assert text.startswith("-- GENERATED by pipeline/export.py. Do not edit.\n")
    assert "Questie" in text and "GPL-3.0-only" in text  # the notice ships with the data
    assert text.endswith(
        'MonkeDB_Meta = { build = "1.60.1.69913", generated = "2026-10-01", count = 5, '
        'schema = 3, prompt = "v1" }\n'
    )
    meta = load_lua(tmp_path).MonkeDB_Meta
    assert (meta.build, meta.generated, meta.count, meta.schema, meta.prompt) == (
        "1.60.1.69913", "2026-10-01", 5, 3, "v1")


def test_meta_defaults(tmp_path: Path) -> None:
    export.write(make_db(), tmp_path, build="")
    meta = load_lua(tmp_path).MonkeDB_Meta
    assert meta.build == "unknown"
    assert len(meta.generated) == 10  # today's date, YYYY-MM-DD


def test_coverage_split(tmp_path: Path) -> None:
    result = export.write(make_db(), tmp_path, build="b", generated="2026-10-01")
    assert result["count"] == 5
    assert result["lore"] == {"vanilla": 2, "new": 0}
    assert result["tasks_only"] == {"vanilla": 2, "new": 1}
    assert result["title_only"] == {"vanilla": 1, "new": 1}
    printed = export.format_coverage(result)
    assert "with lore" in printed and "title only (not exported)" in printed


def test_summary_for_old_quest_text_is_not_exported(tmp_path: Path) -> None:
    conn = make_db()
    add_quest(conn, 214, "Red Silk Bandanas", "Bring 12 Red Silk Bandanas to Scout Riell.",
              "Scout Riell", [("item", "Red Silk Bandana", 12)])
    db.resolve_quests(conn)
    export.write(conn, tmp_path, build="b", generated="2026-10-01")
    record = load_lua(tmp_path).MonkeDB[214]
    assert record.l is None  # the cached lore described the old text
    assert list(record.t.values()) == ["Grab 12 Red Silk Bandana.", "Go back to Scout Riell."]


def test_other_prompt_versions_are_ignored(tmp_path: Path) -> None:
    export.write(make_db(), tmp_path, build="b", generated="2026-10-01", prompt_version="v2")
    g = load_lua(tmp_path)
    assert g.MonkeDB[214].l is None and g.MonkeDB_Meta.prompt == "v2"


def test_a_summary_written_for_other_objectives_is_not_exported(tmp_path: Path) -> None:
    conn = make_db()
    add_summary(conn, 214, S214, stale=True)  # the objectives changed after it was written
    export.write(conn, tmp_path, build="1.60.1.69913", generated="2026-10-01")
    line = next(l for l in (tmp_path / export.DB_FILE).read_text(encoding="utf-8").splitlines() if "[214]" in l)
    assert "l = " not in line and "Grab 10 Red Silk Bandana." in line  # rule-based fallback


def test_delivery_quests_carry_the_d_flag(tmp_path: Path) -> None:
    conn = make_db()
    conn.execute("UPDATE quests SET turnin_kind = 'other' WHERE id = 214")
    export.write(conn, tmp_path, build="b", generated="2026-10-01")
    line = next(l for l in (tmp_path / export.DB_FILE).read_text(encoding="utf-8").splitlines() if "[214]" in l)
    assert 'e = "Scout Riell", d = true, v = 3' in line
    assert "Go see Scout Riell." in line
