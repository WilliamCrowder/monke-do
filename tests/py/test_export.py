def test_bytes_are_utf8_lf_only_and_deterministic(tmp_path: Path) -> None:
    conn = make_db()
    add_summary(conn, 7, {"lore_monke": NASTY, "lore_plain": "x", "tasks": ["a", "b"],
                          "group_line": None})
    export.write(conn, tmp_path / "a", build="b1", generated="2026-10-01")
    export.write(conn, tmp_path / "b", build="b1", generated="2026-10-01")
    for name in (export.DB_FILE, export.META_FILE):
        first = (tmp_path / "a" / name).read_bytes()
        assert first == (tmp_path / "b" / name).read_bytes()
        assert b"\r" not in first and first.endswith(b"\n") and not first.startswith(b"\xef\xbb\xbf")
    assert "café 猫".encode("utf-8") in (tmp_path / "a" / export.DB_FILE).read_bytes()


def test_exported_files_are_valid_lua_51(tmp_path: Path) -> None:
    conn = make_db()
    add_summary(conn, 7, {"lore_monke": NASTY, "lore_plain": "x", "tasks": ["a", "b"],
                          "group_line": None})
    export.write(conn, tmp_path, build="1.60.1.69913", generated="2026-10-01")
    g = load_lua(tmp_path)
    assert g.MonkeDB[214].l == "Scout Riell want 10 Red Silk Bandanas. Monke go get."
    assert g.MonkeDB[214].p == "Scout Riell needs 10 Red Silk Bandanas."
    assert list(g.MonkeDB[214].t.values()) == ["Grab 10 Red Silk Bandana.", "Go back to Scout Riell."]
    assert (g.MonkeDB[214].n, g.MonkeDB[214].e, g.MonkeDB[214].v) == (1, "Scout Riell", 3)
    assert g.MonkeDB[214].g is None
    assert list(g.MonkeDB[214].tp.values()) == ["Collect 10 Red Silk Bandana."]
    assert g.MonkeDB[7].l == NASTY
    assert list(g.MonkeDB[7].tp.values()) == ["Kill 8 Kobold Vermin."]
    assert g.MonkeDB[9].l is None and g.MonkeDB[9].e is None and g.MonkeDB[9].n == 1
    assert g.MonkeDB[301].n is None and g.MonkeDB[301].g == "Bring friends."
    assert g.MonkeDB[301].tp is None
    assert g.MonkeDB[300] is None
    assert sorted(g.MonkeDB.keys()) == [7, 9, 214, 301, 90010]


